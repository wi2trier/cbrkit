"""A CBR system configured by a specification and served over REST, MCP, and the command line.

`System` builds the phases of the CBR cycle from the sections of a `cbrkit.spec.Config`
and serves the cases of a storage such as `cbrkit.io.FileStorage`.
Its methods are the four phases retrieve, reuse, revise, and retain, the whole cycle,
and the maintenance of the case base outside the cycle.
The methods are asynchronous, and `cbrkit.system.operations.operations` turns them into plain typed async functions,
which drive the REST API (`cbrkit.system.api`, extra `api`), the MCP server (`cbrkit.system.mcp`, extra `mcp`),
the `cbrkit` command line (extra `cli`), and the tools of agents alike,
with descriptions and schemas taken from the docstrings and types of the methods.
Every operation takes the query first if it needs one, which retrieve, reuse, and the cycle also take as the key of a stored case,
and returns one envelope, `Outcome`:
the hits with their detailed similarities, broken down on request (`explain`), and the changes of a retain or maintenance run.
The configuration that produced them, with the language models of the providers, is served once,
by `GET /config` of the REST API and the `cbrkit://config` resource of the MCP server.

Providers:
measures and adaptations name their embedders and language models,
and the `providers` section of the sidecar maps these names to Pydantic AI model identifiers without secrets.
`cbrkit.spec.providers` is the one place that turns them into `cbrkit.sim.embed.PydanticAI` and `cbrkit.sim.llm.PydanticAI`,
which needs the `pydantic-ai` extra, with keys and endpoints from the environment variables of the providers.
`System.load` binds the providers section of the sidecar, a `System` built directly only the functions it is given.
A host overrides any name by passing its own function to `System`, `System.load`, or `cbrkit.spec.providers`,
which needs no provider entry and no extra.

Requests only carry cases, queries, keys and numbers:
the case base, the specification and the providers are fixed when the system is built,
and the case base is only written if the specification has a `retain` or `maintain` section.
Keys of retained cases are generated by the storage, and every change is planned on the server from the sidecar.

The REST API has one `POST /<operation>` route per operation, `GET /config` and `GET /health`,
with its documentation at `/docs`.
It answers a refused request (`cbrkit.errors.Refused`, such as a disabled operation) with 400,
a run that lost every race against other writers (`cbrkit.errors.Conflict`) with 409,
and any other failure with 500 without details.
The MCP server has one tool per operation, annotated as read-only unless it writes the case base,
and as destructive if a run may replace or remove stored cases.
`cbrkit serve` binds to the loopback address and checks the Host header by default,
refuses a public address or write operations without a bearer token (`CBRKIT_TOKEN`), and limits the request body size.
`cbrkit.system.api.app` and `cbrkit.system.mcp.server` return the ASGI app and the FastMCP server
to compose with an application of the host.
For agents and retrieval-augmented generation over case bases, see exar.
"""

